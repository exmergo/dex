{#-
  dex_referenced_key: a column test for a column another model references.

  Generated by Dex when a model's declaration names this column in a
  `references` (`customer_id: {references: dim_customers.customer_id}`) and
  `declarations.render_tests` in `.dex/config.yml` turns it on (#1457). A join
  to a key that is not unique multiplies the rows of the model that joins it,
  so the test holds the referenced column unique, on the model the claim is
  about: it is rendered into the parent's YAML entry, not the child's. Where
  the parent declares the column as its whole grain, dbt's `unique` already
  asserts it, and no test is rendered.

  It fails when a non-NULL value appears on more than one row. A NULL is no key
  (it never matches a join), so NULLs never count, as dbt's `unique` ignores
  them. The number is the rows beyond the first of each repeated value.

  `maintain verify` reports the consequence on the model that joins this one
  (`row_fanout`), not this count: fan-out has other causes, so the two are
  held to each other in one direction only (a repeated key here, a fan-out
  there).

  Counts only. The test returns one row holding the number of repeated rows,
  or no row when there are none, and never a key value, so a test
  materialization that samples failing rows (Elementary's) has nothing to keep.
  `fail_calc` makes dbt's `failures` that number.

  One implementation per dialect through dbt's dispatch: the default holds on
  every warehouse Dex supports. Override one dialect with a
  `<adapter>__dex_referenced_key(model, column_name)` macro in the project.
-#}

{% test dex_referenced_key(model, column_name) %}
    {{ config(fail_calc='coalesce(sum(dex_duplicate_rows), 0)') }}
    {{ return(adapter.dispatch('dex_referenced_key')(model, column_name)) }}
{% endtest %}

{% macro default__dex_referenced_key(model, column_name) %}
select dex_duplicate_rows
from (
    select sum(dex_rows) - count(*) as dex_duplicate_rows
    from (
        select count(*) as dex_rows
        from {{ model }}
        where {{ column_name }} is not null
        group by {{ column_name }}
        having count(*) > 1
    ) as dex_groups
) as dex_violations
where dex_duplicate_rows > 0
{% endmacro %}
