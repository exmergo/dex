{#-
  dex_parent_population: a model-level test for a declared parent population.

  Generated by Dex from a model's declaration (`population.parent`: the parent
  model, seed or snapshot, and `key`, each output column mapped to the parent
  column it carries) when `declarations.render_tests` in `.dex/config.yml` turns
  it on (#1454). A declared parent makes two claims, and each is its own test,
  told apart by `direction`:

  - `missing`: every eligible parent key has a row in the model. It fails with
    the number of eligible parent keys the model lacks, `maintain verify`'s
    `parent_population_missing` count (`missing_parents`).
  - `unexpected`: every key in the model is a parent key. It fails with the
    number of the model's keys the parent lacks, `maintain verify`'s
    `parent_population_unexpected` count (`unexpected_keys`).

  Both count distinct keys, and a key with a NULL component on either side is
  no key, as in `maintain verify`. The eligible parent keys are the parent's
  keys that the declaration's `population.filters` keep: a filter applies to
  the parent where the parent has its column (read from the parent's metadata),
  and is skipped where it does not, as `maintain verify` skips it. A skipped
  filter can leave parents the declaration means to exclude counted as missing;
  `maintain verify` says so and lowers its finding to medium, and this test,
  which has no severity of its own, fails. Declare the filter on a column the
  parent has. Where the metadata read finds nothing (an ephemeral parent), every
  filter applies. The `unexpected` direction reads every parent key: a key the
  whole parent lacks is unexpected whatever a filter says.

  A filter compares as `dex_population_filter` does: as text when any listed
  value is text or the parent's column is a text column, and as written
  otherwise. An `excludes` list keeps a parent whose column is NULL; an
  `includes` list does not.

  Counts only. The test returns one row holding the count, or no row when it is
  zero, and never a key, so a test materialization that samples failing rows
  (Elementary's) has nothing to keep. `fail_calc` makes dbt's `failures` that
  count. Both directions scan the model and the parent whole, so the test is
  tagged `dex_scheduled`.

  One implementation per dialect through dbt's dispatch: the default holds on
  every warehouse Dex supports. Override one dialect with a
  `<adapter>__dex_parent_population(model, parent, key, direction, filters)`
  macro in the project. The text cast is dispatched on its own,
  `dex_parent_population_text(column_name)` (ClickHouse uses `toString`, which
  keeps a NULL), and so is a text literal, `dex_parent_population_literal(text)`,
  written as `maintain verify` writes it on each warehouse.
-#}

{% test dex_parent_population(model, parent, key, direction, filters=none) %}
    {{ config(fail_calc='coalesce(sum(dex_violating_keys), 0)') }}
    {{ return(adapter.dispatch('dex_parent_population')(model, parent, key, direction, filters)) }}
{% endtest %}

{% macro default__dex_parent_population(model, parent, key, direction, filters) %}
{%- if direction not in ('missing', 'unexpected') -%}
    {{ exceptions.raise_compiler_error(
        "dex_parent_population on " ~ model ~ " takes direction 'missing' or "
        ~ "'unexpected', not '" ~ direction ~ "'"
    ) }}
{%- endif -%}
{%- if not key -%}
    {{ exceptions.raise_compiler_error(
        "dex_parent_population on " ~ model ~ " maps no key column: give it the "
        ~ "`key` the declaration's population.parent states"
    ) }}
{%- endif -%}
{%- set outs = key.keys() | list -%}
{%- set parents = key.values() | list -%}
{%- set kept = [] -%}
{%- if direction == 'missing' and filters and execute -%}
    {%- set parent_columns = {} -%}
    {%- for column in adapter.get_columns_in_relation(parent) -%}
        {%- do parent_columns.update({column.name | lower: column}) -%}
    {%- endfor -%}
    {%- for rule in filters -%}
        {%- set name = rule['column'] -%}
        {%- set bare = name | replace('"', '') | replace('`', '') | lower -%}
        {%- set found = parent_columns.get(bare) -%}
        {#- A filter on a column the parent does not have is skipped, as
            maintain verify skips it. With no metadata at all, every filter
            applies. -#}
        {%- if found is not none or not parent_columns -%}
            {%- for mode in ('includes', 'excludes') if rule.get(mode) -%}
                {%- set values = rule[mode] -%}
                {%- set as_text = namespace(on=false) -%}
                {%- for value in values if value is string -%}
                    {%- set as_text.on = true -%}
                {%- endfor -%}
                {%- set string_column = found is not none and found.is_string() -%}
                {%- if string_column -%}
                    {%- set as_text.on = true -%}
                {%- endif -%}
                {%- set literals = [] -%}
                {%- for value in values -%}
                    {%- if as_text.on -%}
                        {%- if value is boolean -%}
                            {%- set text = 'true' if value else 'false' -%}
                        {%- else -%}
                            {%- set text = value | string -%}
                        {%- endif -%}
                        {%- do literals.append(adapter.dispatch('dex_parent_population_literal')(text)) -%}
                    {%- elif value is boolean -%}
                        {%- do literals.append('TRUE' if value else 'FALSE') -%}
                    {%- else -%}
                        {%- do literals.append(value | string) -%}
                    {%- endif -%}
                {%- endfor -%}
                {%- set subject = name -%}
                {%- if as_text.on and not string_column -%}
                    {%- set subject = adapter.dispatch('dex_parent_population_text')(name) -%}
                {%- endif -%}
                {%- if mode == 'excludes' -%}
                    {%- do kept.append('(' ~ name ~ ' is null or ' ~ subject ~ ' not in (' ~ literals | join(', ') ~ '))') -%}
                {%- else -%}
                    {%- do kept.append(subject ~ ' in (' ~ literals | join(', ') ~ ')') -%}
                {%- endif -%}
            {%- endfor -%}
        {%- endif -%}
    {%- endfor -%}
{%- endif -%}
{%- if direction == 'missing' -%}
    {%- set expected_relation, expected_columns = parent, parents -%}
    {%- set present_relation, present_columns = model, outs -%}
{%- else -%}
    {%- set expected_relation, expected_columns = model, outs -%}
    {%- set present_relation, present_columns = parent, parents -%}
{%- endif -%}
{%- set expected_where = [] -%}
{%- for column in expected_columns -%}
    {%- do expected_where.append(column ~ ' is not null') -%}
{%- endfor -%}
{%- do expected_where.extend(kept) -%}
{%- set present_where = [] -%}
{%- for column in present_columns -%}
    {%- do present_where.append(column ~ ' is not null') -%}
{%- endfor -%}
select dex_violating_keys
from (
    select count(*) - count(case when dex_present.dex_hit = 1 then 1 end) as dex_violating_keys
    from (
        select distinct
        {%- for column in expected_columns %}
            {{ column }} as dex_k{{ loop.index0 }}{{ ',' if not loop.last }}
        {%- endfor %}
        from {{ expected_relation }}
        where {{ expected_where | join(' and ') }}
    ) as dex_expected
    left join (
        select distinct
        {%- for column in present_columns %}
            {{ column }} as dex_k{{ loop.index0 }},
        {%- endfor %}
            1 as dex_hit
        from {{ present_relation }}
        where {{ present_where | join(' and ') }}
    ) as dex_present
    on {% for column in expected_columns -%}
        dex_expected.dex_k{{ loop.index0 }} = dex_present.dex_k{{ loop.index0 }}{{ ' and ' if not loop.last }}
    {%- endfor %}
) as dex_violations
where dex_violating_keys > 0
{% endmacro %}

