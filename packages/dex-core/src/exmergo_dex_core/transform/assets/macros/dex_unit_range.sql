{#-
  dex_unit_range: a column test for a column declared a fraction.

  Generated by Dex from a model's declaration (`unit: fraction` on a column)
  when `declarations.render_tests` in `.dex/config.yml` turns it on (#1455). It
  fails when a non-NULL value sits below 0 or above 1, and agrees with
  `maintain verify`'s unit check (`unit_out_of_range`), row for row. A NULL is
  no value, so it never breaks the range, and a column holding only NULLs
  passes, where `maintain verify` notes it as not checked.

  A column declared `percent` renders no test: `maintain verify` flags a percent
  whose every value sits within 0 to 1, which is what a fraction stored as a
  percent looks like and also what a column of genuinely small percentages
  looks like, so that check stays a question `maintain verify` asks rather than
  a test that fails a run.

  The test reads the column's type from the relation's metadata. A column that
  is not a number (text, a boolean, a date, a UUID, JSON) is not checked,
  because `maintain verify` does not check it either and a comparison with a
  number would error on some warehouses; where the metadata read finds nothing
  (an ephemeral model, a mutant `transform test --mutate` builds), the column
  is compared as it is.

  Counts only. The test returns one row holding the number of rows outside the
  range, or no row when none is, and never a value from the column, so a test
  materialization that samples failing rows (Elementary's) has nothing to keep.
  `fail_calc` makes dbt's `failures` that number, the `out_of_range_rows`
  `maintain verify` reports.

  One implementation per dialect through dbt's dispatch: the default holds on
  every warehouse Dex supports. Override one dialect with a
  `<adapter>__dex_unit_range(model, column_name)` macro in the project.
-#}

{% test dex_unit_range(model, column_name) %}
    {{ config(fail_calc='coalesce(sum(dex_violating_rows), 0)') }}
    {{ return(adapter.dispatch('dex_unit_range')(model, column_name)) }}
{% endtest %}

{% macro default__dex_unit_range(model, column_name) %}
{%- set checked = namespace(on=true) -%}
{#- The metadata names a column unquoted; a `quote: true` column arrives quoted. -#}
{%- set dex_name = column_name | replace('"', '') | replace('`', '') -%}
{%- if execute -%}
    {%- for column in adapter.get_columns_in_relation(model)
        if column.name | lower == dex_name | lower -%}
        {#- A number is read as `maintain verify` reads one
            (`explore/profile.py::is_numeric_type`): a numeric hint in the type,
            and no boolean or temporal one. `NUMBER` is Snowflake's spelling in
            dbt's metadata, where verify reads `FIXED`. dbt's own `is_number()`
            is not used: it reads `DECIMAL(2,1)`, `FLOAT64` and `NUMBER(38,0)`
            as no number. -#}
        {%- set dtype = column.dtype | upper -%}
        {%- set numeric = namespace(on=false) -%}
        {%- for hint in ['INT', 'DECIMAL', 'NUMERIC', 'NUMBER', 'DOUBLE', 'FLOAT',
            'REAL', 'HUGEINT', 'FIXED'] if hint in dtype -%}
            {%- set numeric.on = true -%}
        {%- endfor -%}
        {%- for hint in ['BOOL', 'DATE', 'TIME', 'INTERVAL'] if hint in dtype -%}
            {%- set numeric.on = false -%}
        {%- endfor -%}
        {%- if not numeric.on -%}
            {%- set checked.on = false -%}
        {%- endif -%}
    {%- endfor -%}
{%- endif -%}
select dex_violating_rows
from (
    select count(*) as dex_violating_rows
    from {{ model }}
    {%- if checked.on %}
    where {{ column_name }} < 0 or {{ column_name }} > 1
    {%- else %}
    where 1 = 0
    {%- endif %}
) as dex_violations
where dex_violating_rows > 0
{% endmacro %}
