{#-
  dex_unique_combination: a model-level test for a declared composite grain.

  Generated by Dex from a model's declaration (`grain: [a, b]`) when
  `declarations.render_tests` in `.dex/config.yml` turns it on (#1452). It fails
  when two rows share the declared grain, and agrees with `maintain verify`'s
  grain check (`grain_broken`): both count the rows beyond the first of each
  grain value, rows minus distinct grain values, and both treat a NULL in a
  grain column as a value, so two rows (1, NULL) are a duplicate.

  Counts only. The test returns one row holding the number of duplicate rows,
  or no row when there are none, and never a key value, so a test
  materialization that samples failing rows (Elementary's) has nothing to keep.
  `fail_calc` makes dbt's `failures` that number, the same number
  `maintain verify` reports.

  One implementation per dialect through dbt's dispatch: the default holds on
  every warehouse Dex supports. Override one dialect with a
  `<adapter>__dex_unique_combination(model, columns)` macro in the project.
-#}

{% test dex_unique_combination(model, columns) %}
    {{ config(fail_calc='coalesce(sum(dex_duplicate_rows), 0)') }}
    {{ return(adapter.dispatch('dex_unique_combination')(model, columns)) }}
{% endtest %}

{% macro default__dex_unique_combination(model, columns) %}
select dex_duplicate_rows
from (
    select sum(dex_rows) - count(*) as dex_duplicate_rows
    from (
        select count(*) as dex_rows
        from {{ model }}
        group by {{ columns | join(', ') }}
        having count(*) > 1
    ) as dex_groups
) as dex_violations
where dex_duplicate_rows > 0
{% endmacro %}
