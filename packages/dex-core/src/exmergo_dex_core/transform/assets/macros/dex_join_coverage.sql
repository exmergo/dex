{#-
  dex_join_coverage: a model-level test for a join the declaration requires.

  Generated by Dex from a model's declaration when `declarations.render_tests`
  in `.dex/config.yml` turns it on (#1456). A column that carries the model's
  join key and declares a `references` naming the joined model makes that join
  required: every eligible row of the join's driving input must find a parent
  row. `maintain verify` holds the join to that claim at threshold zero
  (`join_orphans`, `join_zero_overlap`, `join_no_match`), and this test says the
  same thing in the build.

  It renders for an INNER join, and for a LEFT join to a parent the model
  filters first (which `relationships`, reading the whole parent, misses). An
  INNER join drops the rows it cannot match, so the model's output, and the
  `relationships` test on it, never shows them; this test reads the join's two
  inputs instead, as Dex read them from the model's SQL when the plan rendered
  it:

  - `child` and `child_columns`: the relation the join's key is read from (the
    driving input) and the key columns, in order;
  - `parent` and `parent_columns`: the joined relation and its key columns;
  - `child_where` and `parent_where`: the row filters the model applies to each
    side before joining it (a staging CTE's WHERE), so a row the model never
    joins is never counted;
  - `null_keys`: `excluded` (the default) leaves a row with a NULL key
    component out, a missing reference both checks accept; `unmatched` counts
    it as unmatched, where the key column is declared `null_rule: never`.

  It fails with the number of eligible driving rows that find no parent row,
  `maintain verify`'s `unmatched_rows`, and matches the parent's DISTINCT keys
  through a hit flag, so a duplicated parent key never multiplies a row and a
  warehouse that fills an unmatched column with a default still counts a miss.

  Counts only. The test returns one row holding the count, or no row when it is
  zero, and never a key, so a test materialization that samples failing rows
  (Elementary's) has nothing to keep. `fail_calc` makes dbt's `failures` that
  count. It scans both inputs whole, an anti-join, so it is tagged
  `dex_scheduled`.

  The arguments describe the join as the model wrote it when the plan rendered
  the test. A later plan that changes the join reports this test `stale` under
  `data.generated_tests`; remove it then.

  One implementation per dialect through dbt's dispatch: the default holds on
  every warehouse Dex supports. Override one dialect with a
  `<adapter>__dex_join_coverage(model, child, child_columns, parent,
  parent_columns, child_where, parent_where, null_keys)` macro in the project.
-#}

{% test dex_join_coverage(model, child, child_columns, parent, parent_columns, child_where=none, parent_where=none, null_keys='excluded') %}
    {{ config(fail_calc='coalesce(sum(dex_unmatched_rows), 0)') }}
    {{ return(adapter.dispatch('dex_join_coverage')(model, child, child_columns, parent, parent_columns, child_where, parent_where, null_keys)) }}
{% endtest %}

{% macro default__dex_join_coverage(model, child, child_columns, parent, parent_columns, child_where, parent_where, null_keys) %}
{%- if not child_columns or not parent_columns or child_columns | length != parent_columns | length -%}
    {{ exceptions.raise_compiler_error(
        "dex_join_coverage on " ~ model ~ " needs child_columns and "
        ~ "parent_columns of the same length, one per key column of the join"
    ) }}
{%- endif -%}
{%- if null_keys not in ('excluded', 'unmatched') -%}
    {{ exceptions.raise_compiler_error(
        "dex_join_coverage on " ~ model ~ " takes null_keys 'excluded' or "
        ~ "'unmatched', not '" ~ null_keys ~ "'"
    ) }}
{%- endif -%}
{%- set present = [] -%}
{%- set absent = [] -%}
{%- for column in child_columns -%}
    {%- do present.append('dex_child.dex_k' ~ loop.index0 ~ ' is not null') -%}
    {%- do absent.append('dex_child.dex_k' ~ loop.index0 ~ ' is null') -%}
{%- endfor -%}
select dex_unmatched_rows
from (
    select count(*) as dex_unmatched_rows
    from (
        select
        {%- for column in child_columns %}
            {{ column }} as dex_k{{ loop.index0 }}{{ ',' if not loop.last }}
        {%- endfor %}
        from {{ child }}
        {%- if child_where %}
        where {{ child_where }}
        {%- endif %}
    ) as dex_child
    left join (
        select distinct
        {%- for column in parent_columns %}
            {{ column }} as dex_k{{ loop.index0 }},
        {%- endfor %}
            1 as dex_hit
        from {{ parent }}
        {%- if parent_where %}
        where {{ parent_where }}
        {%- endif %}
    ) as dex_parent
    on {% for column in child_columns -%}
        dex_child.dex_k{{ loop.index0 }} = dex_parent.dex_k{{ loop.index0 }}{{ ' and ' if not loop.last }}
    {%- endfor %}
    where ({{ present | join(' and ') }} and coalesce(dex_parent.dex_hit, 0) <> 1)
    {%- if null_keys == 'unmatched' %}
        or ({{ absent | join(' or ') }})
    {%- endif %}
) as dex_violations
where dex_unmatched_rows > 0
{% endmacro %}
