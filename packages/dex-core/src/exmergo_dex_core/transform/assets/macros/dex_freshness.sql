{#-
  dex_freshness: a column test for a time column's declared freshness.

  Generated by Dex from a model's declaration (`freshness: {max_lag, basis}` on
  the column with role `time`) when `declarations.render_tests` in
  `.dex/config.yml` turns it on (#1460). It fails when the column's newest value
  trails the warehouse's clock by more than `max_lag_seconds`, and when the
  column holds no value at all (an empty model, or a column NULL on every row):
  no rows is not fresh. It agrees with `maintain verify`'s `freshness_exceeded`,
  which sends the same expressions.

  The clock is the warehouse's, read in the same statement as the column's
  newest value, never the machine running dbt. Each side is a whole number of
  seconds since the Unix epoch, floored on its own, so a value exactly
  `max_lag_seconds` behind the clock passes. A timestamp with no time zone is
  read as UTC, as dbt's source freshness reads one, and a date as its UTC
  midnight (declare a lag of a day or more on a date column). A newest value
  ahead of the clock passes.

  The declaration's `basis` (`business` or `capture`) is not an argument: the
  test fails alike on both. `maintain verify` reads it to say how loud a stale
  column is.

  The test reads the column's type from the relation's metadata. A column that
  is no date or timestamp is an error, not a pass, since no lag can be read from
  it. Where the metadata read finds nothing (an ephemeral model), the column is
  read as an instant.

  Counts only. The test counts the rows within the limit and never computes the
  column's newest value, so neither it nor the lag (which would disclose that
  value) is computed or returned, on any column, personal data included. It
  returns at most one row, holding 1 and the limit, so a stored or sampled
  failing row (dbt's `store_failures`, Elementary's samples) keeps nothing from
  the column. `fail_calc` makes dbt's `failures` 1 for a stale column.

  One implementation per dialect through dbt's dispatch, with two pieces
  dispatched on their own: `dex_freshness_epoch(expression, kind)` (whole epoch
  seconds of a date or timestamp; `kind` is `date`, `ntz`, `tz` or `unknown`) and
  `dex_freshness_now()` (the warehouse's clock in whole epoch seconds). Override
  one dialect with a `<adapter>__dex_freshness_epoch(...)` macro in the project.
-#}

{% test dex_freshness(model, column_name, max_lag_seconds) %}
    {{ config(fail_calc='coalesce(sum(dex_violating_rows), 0)') }}
    {{ return(adapter.dispatch('dex_freshness')(model, column_name, max_lag_seconds)) }}
{% endtest %}

{% macro default__dex_freshness(model, column_name, max_lag_seconds) %}
{%- set limit = max_lag_seconds | int -%}
{%- if limit <= 0 -%}
    {{ exceptions.raise_compiler_error(
        "dex_freshness on " ~ model ~ " takes max_lag_seconds, a whole number of "
        ~ "seconds above zero, not '" ~ max_lag_seconds ~ "'"
    ) }}
{%- endif -%}
{#- The declared name resolved to its physical spelling and quoted, as
    maintain verify matches it against the live columns, case folded. -#}
{%- set columns = {} -%}
{%- if execute -%}
    {%- for column in adapter.get_columns_in_relation(model) -%}
        {%- do columns.update({column.name | lower: column}) -%}
    {%- endfor -%}
{%- endif -%}
{%- set bare = column_name | replace('"', '') | replace('`', '') -%}
{%- set found = columns.get(bare | lower) -%}
{%- if found is not none -%}
    {%- set name = adapter.quote(found.name) -%}
    {%- set kind = dex_freshness_kind(found.dtype) -%}
    {%- if kind is none -%}
        {{ exceptions.raise_compiler_error(
            "dex_freshness: " ~ model ~ "." ~ bare ~ " is " ~ found.dtype
            ~ ", not a date or timestamp, so no lag can be read from it"
        ) }}
    {%- endif -%}
{%- elif columns -%}
    {{ exceptions.raise_compiler_error(
        "dex_freshness: the declaration names column '" ~ bare ~ "', which "
        ~ model ~ " does not have"
    ) }}
{%- else -%}
    {%- set name = adapter.quote(bare) -%}
    {%- set kind = 'unknown' -%}
{%- endif -%}
{#- The rows within the limit of the clock, each row's lag floored as
    maintain verify floors the newest one's: the column is fresh exactly where
    one is, and the newest value itself is never computed. -#}
{%- set row_epoch = adapter.dispatch('dex_freshness_epoch')(name, kind) -%}
{%- set now = adapter.dispatch('dex_freshness_now')() -%}
select dex_violating_rows, dex_max_lag_seconds
from (
    select
        case when dex_values = 0 or dex_fresh_rows = 0 then 1 else 0 end
            as dex_violating_rows,
        {{ limit }} as dex_max_lag_seconds
    from (
        select
            count({{ name }}) as dex_values,
            count(case when ({{ now }}) - ({{ row_epoch }}) <= {{ limit }} then 1 end)
                as dex_fresh_rows
        from {{ model }}
    ) as dex_window
) as dex_freshness
where dex_violating_rows > 0
{% endmacro %}

{#- `date`, `ntz` (a timestamp with no time zone), `tz` (an instant), or none
    where the type is no date or timestamp; `maintain/freshness.py`'s
    `temporal_kind` reads a type the same way. -#}
{% macro dex_freshness_kind(dtype) -%}
    {%- set upper = (dtype or '') | upper -%}
    {%- if 'INTERVAL' in upper -%}
        {{- return(none) -}}
    {%- elif 'TIMESTAMP' in upper or 'DATETIME' in upper -%}
        {%- if 'WITHOUT TIME ZONE' in upper or 'NTZ' in upper -%}
            {{- return('ntz') -}}
        {%- elif 'WITH TIME ZONE' in upper or 'WITH LOCAL TIME ZONE' in upper
              or 'TIMESTAMPTZ' in upper or 'TIMESTAMP_TZ' in upper
              or 'TIMESTAMP_LTZ' in upper -%}
            {{- return('tz') -}}
        {%- elif target.type in ('databricks', 'spark', 'clickhouse') -%}
            {{- return('tz') -}}
        {%- elif target.type == 'bigquery' -%}
            {{- return('ntz' if 'DATETIME' in upper else 'tz') -}}
        {%- else -%}
            {{- return('ntz') -}}
        {%- endif -%}
    {%- elif 'DATE' in upper -%}
        {{- return('date') -}}
    {%- else -%}
        {{- return(none) -}}
    {%- endif -%}
{%- endmacro %}

{# --- whole epoch seconds of a date or timestamp, a zone-less value as UTC --- #}

{% macro default__dex_freshness_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        cast(floor(epoch(cast({{ expression }} as timestamp))) as bigint)
    {%- else -%}
        cast(floor(epoch({{ expression }})) as bigint)
    {%- endif -%}
{%- endmacro %}

{% macro postgres__dex_freshness_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        cast(floor(extract(epoch from cast({{ expression }} as timestamp))) as bigint)
    {%- else -%}
        cast(floor(extract(epoch from {{ expression }})) as bigint)
    {%- endif -%}
{%- endmacro %}

{% macro redshift__dex_freshness_epoch(expression, kind) -%}
    {{- postgres__dex_freshness_epoch(expression, kind) -}}
{%- endmacro %}

{% macro bigquery__dex_freshness_epoch(expression, kind) -%}
    {#- CAST reads a DATE or DATETIME as UTC and keeps a TIMESTAMP as it is. -#}
    unix_seconds(cast({{ expression }} as timestamp))
{%- endmacro %}

{% macro snowflake__dex_freshness_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        date_part(epoch_second, cast({{ expression }} as timestamp_ntz))
    {%- else -%}
        date_part(epoch_second, {{ expression }})
    {%- endif -%}
{%- endmacro %}

{% macro databricks__dex_freshness_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        cast(unix_date({{ expression }}) as bigint) * 86400
    {%- elif kind == 'ntz' -%}
        {#- A TIMESTAMP_NTZ's wall clock read as UTC, whatever the session's
            time zone, which a cast to TIMESTAMP would apply. -#}
        cast(unix_date(cast({{ expression }} as date)) as bigint) * 86400 + hour({{ expression }}) * 3600 + minute({{ expression }}) * 60 + cast(floor(second({{ expression }})) as bigint)
    {%- else -%}
        unix_seconds(cast({{ expression }} as timestamp))
    {%- endif -%}
{%- endmacro %}

{% macro spark__dex_freshness_epoch(expression, kind) -%}
    {{- databricks__dex_freshness_epoch(expression, kind) -}}
{%- endmacro %}

{% macro clickhouse__dex_freshness_epoch(expression, kind) -%}
    toInt64(toUnixTimestamp(toDateTime({{ expression }}, 'UTC')))
{%- endmacro %}

{% macro trino__dex_freshness_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        cast(floor(to_unixtime(with_timezone(cast({{ expression }} as timestamp), 'UTC'))) as bigint)
    {%- elif kind == 'ntz' -%}
        cast(floor(to_unixtime(with_timezone({{ expression }}, 'UTC'))) as bigint)
    {%- else -%}
        cast(floor(to_unixtime({{ expression }})) as bigint)
    {%- endif -%}
{%- endmacro %}

{# --- the warehouse's clock in whole epoch seconds --- #}

{% macro default__dex_freshness_now() -%}
    cast(floor(epoch(current_timestamp)) as bigint)
{%- endmacro %}

{% macro postgres__dex_freshness_now() -%}
    cast(floor(extract(epoch from current_timestamp)) as bigint)
{%- endmacro %}

{% macro redshift__dex_freshness_now() -%}
    cast(floor(extract(epoch from getdate())) as bigint)
{%- endmacro %}

{% macro bigquery__dex_freshness_now() -%}
    unix_seconds(current_timestamp())
{%- endmacro %}

{% macro snowflake__dex_freshness_now() -%}
    date_part(epoch_second, current_timestamp())
{%- endmacro %}

{% macro databricks__dex_freshness_now() -%}
    unix_seconds(current_timestamp())
{%- endmacro %}

{% macro spark__dex_freshness_now() -%}
    {{- databricks__dex_freshness_now() -}}
{%- endmacro %}

{% macro clickhouse__dex_freshness_now() -%}
    toInt64(toUnixTimestamp(now()))
{%- endmacro %}

{% macro trino__dex_freshness_now() -%}
    cast(floor(to_unixtime(current_timestamp)) as bigint)
{%- endmacro %}
