{#-
  dex_continuity: a column test for gaps in a declared time column.

  Generated by Dex from a model's declaration (`continuity: {grain, by}` on the
  column with role `time`) when `declarations.render_tests` in
  `.dex/config.yml` turns it on (#1461). It fails with the number of gaps in
  the column: a gap is a run of one or more buckets at `grain` that hold no
  row, between two buckets that do. With `by`, the gaps are searched per value
  of those columns, so a key missing from one day another key has rows on is a
  gap for that key. A bucket at the edge of the data (before the first row or
  after the last) is never a gap, so the answer does not depend on today's
  date: whether data stopped too long ago is `dex_freshness`'s question.

  Grains: `second`, `minute`, `hour`, `day`, `week` (the ISO week, starting
  Monday), `month`, `quarter` and `year`. Each value is read in UTC, as
  `dex_freshness` reads it: a timestamp with no time zone as UTC, a date as
  its UTC midnight. A bucket is a whole number computed from the value's epoch
  seconds (calendar grains through the civil date of its day), so no date
  spine is built and no session time zone or week-start setting is read. A
  grain finer than a day on a date column is an error, since every day would
  show its hours as gaps, and so is a column that is no date or timestamp.
  The type is read from the relation's metadata; where that read finds nothing
  (an ephemeral model) the column is read as an instant, so a date there is its
  UTC midnight and a sub-day grain cannot be refused.

  NULL times are left out. A NULL `by` value is a key of its own.

  Counts only. The test returns one row holding the number of gaps, or no row
  when there are none, and never a date or a key, so a stored or sampled
  failing row keeps nothing from the data. `fail_calc` makes dbt's `failures`
  that number.

  Cost: one scan of the model and a sort over its distinct (key, bucket)
  pairs, which is why the test is tagged `dex_scheduled`.

  One implementation per dialect through dbt's dispatch, with pieces
  dispatched on their own: `dex_continuity_epoch(expression, kind)` (whole
  epoch seconds, the same expressions `dex_freshness` uses),
  `dex_continuity_floordiv(numerator, denominator)` and
  `dex_continuity_lag(expression, partition_by, order_by)`. Override one
  dialect with a `<adapter>__dex_continuity_<piece>(...)` macro in the project.
-#}

{% test dex_continuity(model, column_name, grain='day', by=[]) %}
    {{ config(fail_calc='coalesce(sum(dex_gaps), 0)') }}
    {{ return(adapter.dispatch('dex_continuity')(model, column_name, grain, by)) }}
{% endtest %}

{% macro default__dex_continuity(model, column_name, grain, by) %}
{%- set grains = ['second', 'minute', 'hour', 'day', 'week', 'month', 'quarter', 'year'] -%}
{%- if grain not in grains -%}
    {{ exceptions.raise_compiler_error(
        "dex_continuity on " ~ model ~ " takes a grain of " ~ grains | join(', ')
        ~ ", not '" ~ grain ~ "'"
    ) }}
{%- endif -%}
{%- set keys = [by] if by is string else (by or []) -%}
{#- Each declared name resolved to its physical spelling and quoted, case
    folded, as dex_freshness resolves its column. -#}
{%- set columns = {} -%}
{%- if execute -%}
    {%- for column in adapter.get_columns_in_relation(model) -%}
        {%- do columns.update({column.name | lower: column}) -%}
    {%- endfor -%}
{%- endif -%}
{%- set resolved = [] -%}
{%- for declared in [column_name] + keys -%}
    {%- set bare = declared | replace('"', '') | replace('`', '') -%}
    {%- set found = columns.get(bare | lower) -%}
    {%- if found is not none -%}
        {%- do resolved.append((adapter.quote(found.name), found.dtype)) -%}
    {%- elif columns -%}
        {{ exceptions.raise_compiler_error(
            "dex_continuity: the declaration names column '" ~ bare ~ "', which "
            ~ model ~ " does not have"
        ) }}
    {%- else -%}
        {%- do resolved.append((adapter.quote(bare), none)) -%}
    {%- endif -%}
{%- endfor -%}
{%- set name = resolved[0][0] -%}
{%- if resolved[0][1] is not none -%}
    {%- set kind = dex_continuity_kind(resolved[0][1]) -%}
    {%- if kind is none -%}
        {{ exceptions.raise_compiler_error(
            "dex_continuity: " ~ model ~ "." ~ column_name ~ " is " ~ resolved[0][1]
            ~ ", not a date or timestamp, so it has no buckets to search"
        ) }}
    {%- endif -%}
{%- else -%}
    {%- set kind = 'unknown' -%}
{%- endif -%}
{%- if kind == 'date' and grain in ('second', 'minute', 'hour') -%}
    {{ exceptions.raise_compiler_error(
        "dex_continuity: " ~ model ~ "." ~ column_name ~ " is a date, so it cannot "
        ~ "be searched for gaps by the " ~ grain ~ "; declare a grain of a day or more"
    ) }}
{%- endif -%}
{%- set key_names = [] -%}
{%- for pair in resolved[1:] -%}
    {%- do key_names.append(pair[0]) -%}
{%- endfor -%}
{%- set key_list = key_names | join(', ') -%}
{%- set carry = (key_list ~ ', ') if key_names else '' -%}
{%- set div = adapter.dispatch('dex_continuity_floordiv') -%}
{%- set epoch = adapter.dispatch('dex_continuity_epoch')(name, kind) -%}
{%- if grain == 'second' -%}
    {%- set bucket = 'dex_epoch' -%}
{%- elif grain == 'minute' -%}
    {%- set bucket = div('dex_epoch', 60) -%}
{%- elif grain == 'hour' -%}
    {%- set bucket = div('dex_epoch', 3600) -%}
{%- elif grain == 'day' -%}
    {%- set bucket = div('dex_epoch', 86400) -%}
{%- elif grain == 'week' -%}
    {#- 1970-01-01 was a Thursday: three days on, the weeks start on Monday. -#}
    {%- set bucket = div(div('dex_epoch', 86400) ~ ' + 3', 7) -%}
{%- elif grain == 'month' -%}
    {%- set bucket = 'dex_year * 12 + dex_month - 1' -%}
{%- elif grain == 'quarter' -%}
    {%- set bucket = 'dex_year * 4 + ' ~ div('dex_month - 1', 3) -%}
{%- else -%}
    {%- set bucket = 'dex_year' -%}
{%- endif -%}
{%- set order_by = 'dex_bucket' -%}
select dex_gaps
from (
    select count(*) as dex_gaps
    from (
        select dex_bucket,
            {{ adapter.dispatch('dex_continuity_lag')('dex_bucket', key_list, order_by) }}
                as dex_previous
        from (
            select distinct {{ carry }}{{ bucket }} as dex_bucket
            from (
{%- if grain in ('month', 'quarter', 'year') %}
                {{ dex_continuity_civil(model, name, epoch, carry) }}
{%- else %}
                select {{ carry }}{{ epoch }} as dex_epoch
                from {{ model }}
                where {{ name }} is not null
{%- endif %}
            ) as dex_values
        ) as dex_buckets
    ) as dex_steps
    where dex_bucket - dex_previous > 1
) as dex_continuity
where dex_gaps > 0
{% endmacro %}

{#- The civil year and month of each value's UTC day, from its days since the
    epoch (H. Hinnant's days-to-civil), one step per subquery so each column is
    computed once. Every division is a floor division of whole numbers. -#}
{% macro dex_continuity_civil(model, name, epoch, carry) -%}
{%- set div = adapter.dispatch('dex_continuity_floordiv') -%}
select {{ carry }}dex_y + case when dex_m <= 2 then 1 else 0 end as dex_year,
    dex_m as dex_month
from (
    select {{ carry }}dex_y,
        case when dex_mp < 10 then dex_mp + 3 else dex_mp - 9 end as dex_m
    from (
        select {{ carry }}dex_yoe + dex_era * 400 as dex_y,
            {{ div('5 * (dex_doe - (365 * dex_yoe + ' ~ div('dex_yoe', 4) ~ ' - ' ~ div('dex_yoe', 100) ~ ')) + 2', 153) }} as dex_mp
        from (
            select {{ carry }}dex_era, dex_doe,
                {{ div('dex_doe - ' ~ div('dex_doe', 1460) ~ ' + ' ~ div('dex_doe', 36524) ~ ' - ' ~ div('dex_doe', 146096), 365) }} as dex_yoe
            from (
                select {{ carry }}dex_era, dex_z - dex_era * 146097 as dex_doe
                from (
                    select {{ carry }}dex_z, {{ div('dex_z', 146097) }} as dex_era
                    from (
                        select {{ carry }}{{ div(epoch, 86400) }} + 719468 as dex_z
                        from {{ model }}
                        where {{ name }} is not null
                    ) as dex_days
                ) as dex_eras
            ) as dex_eras_days
        ) as dex_years_of_era
    ) as dex_month_points
) as dex_civil
{%- endmacro %}

{#- `date`, `ntz` (a timestamp with no time zone), `tz` (an instant), or none
    where the type is no date or timestamp, read as dex_freshness reads it. -#}
{% macro dex_continuity_kind(dtype) -%}
    {%- set upper = (dtype or '') | upper -%}
    {%- if 'INTERVAL' in upper -%}
        {{- return(none) -}}
    {%- elif 'TIMESTAMP' in upper or 'DATETIME' in upper -%}
        {%- if 'WITHOUT TIME ZONE' in upper or 'NTZ' in upper -%}
            {{- return('ntz') -}}
        {%- elif 'WITH TIME ZONE' in upper or 'WITH LOCAL TIME ZONE' in upper
              or 'TIMESTAMPTZ' in upper or 'TIMESTAMP_TZ' in upper
              or 'TIMESTAMP_LTZ' in upper -%}
            {{- return('tz') -}}
        {%- elif target.type in ('databricks', 'spark', 'clickhouse') -%}
            {{- return('tz') -}}
        {%- elif target.type == 'bigquery' -%}
            {{- return('ntz' if 'DATETIME' in upper else 'tz') -}}
        {%- else -%}
            {{- return('ntz') -}}
        {%- endif -%}
    {%- elif 'DATE' in upper -%}
        {{- return('date') -}}
    {%- else -%}
        {{- return(none) -}}
    {%- endif -%}
{%- endmacro %}

{# --- whole epoch seconds of a date or timestamp, a zone-less value as UTC, the
    same expressions dex_freshness sends --- #}

{% macro default__dex_continuity_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        cast(floor(epoch(cast({{ expression }} as timestamp))) as bigint)
    {%- else -%}
        cast(floor(epoch({{ expression }})) as bigint)
    {%- endif -%}
{%- endmacro %}

{% macro postgres__dex_continuity_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        cast(floor(extract(epoch from cast({{ expression }} as timestamp))) as bigint)
    {%- else -%}
        cast(floor(extract(epoch from {{ expression }})) as bigint)
    {%- endif -%}
{%- endmacro %}

{% macro redshift__dex_continuity_epoch(expression, kind) -%}
    {{- postgres__dex_continuity_epoch(expression, kind) -}}
{%- endmacro %}

{% macro bigquery__dex_continuity_epoch(expression, kind) -%}
    {#- CAST reads a DATE or DATETIME as UTC and keeps a TIMESTAMP as it is. -#}
    unix_seconds(cast({{ expression }} as timestamp))
{%- endmacro %}

{% macro snowflake__dex_continuity_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        date_part(epoch_second, cast({{ expression }} as timestamp_ntz))
    {%- else -%}
        date_part(epoch_second, {{ expression }})
    {%- endif -%}
{%- endmacro %}

{% macro databricks__dex_continuity_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        cast(unix_date({{ expression }}) as bigint) * 86400
    {%- elif kind == 'ntz' -%}
        {#- A TIMESTAMP_NTZ's wall clock read as UTC, whatever the session's
            time zone, which a cast to TIMESTAMP would apply. -#}
        cast(unix_date(cast({{ expression }} as date)) as bigint) * 86400 + hour({{ expression }}) * 3600 + minute({{ expression }}) * 60 + cast(floor(second({{ expression }})) as bigint)
    {%- else -%}
        unix_seconds(cast({{ expression }} as timestamp))
    {%- endif -%}
{%- endmacro %}

{% macro spark__dex_continuity_epoch(expression, kind) -%}
    {{- databricks__dex_continuity_epoch(expression, kind) -}}
{%- endmacro %}

{% macro clickhouse__dex_continuity_epoch(expression, kind) -%}
    toInt64(toUnixTimestamp(toDateTime({{ expression }}, 'UTC')))
{%- endmacro %}

{% macro trino__dex_continuity_epoch(expression, kind) -%}
    {%- if kind == 'date' -%}
        cast(floor(to_unixtime(with_timezone(cast({{ expression }} as timestamp), 'UTC'))) as bigint)
    {%- elif kind == 'ntz' -%}
        cast(floor(to_unixtime(with_timezone({{ expression }}, 'UTC'))) as bigint)
    {%- else -%}
        cast(floor(to_unixtime({{ expression }})) as bigint)
    {%- endif -%}
{%- endmacro %}

{# --- floor division of whole numbers, exact for every bucket Dex computes --- #}

{% macro default__dex_continuity_floordiv(numerator, denominator) -%}
cast(floor(cast({{ numerator }} as double) / {{ denominator }}) as bigint)
{%- endmacro %}

{% macro postgres__dex_continuity_floordiv(numerator, denominator) -%}
cast(floor(cast({{ numerator }} as double precision) / {{ denominator }}) as bigint)
{%- endmacro %}

{% macro redshift__dex_continuity_floordiv(numerator, denominator) -%}
{{- postgres__dex_continuity_floordiv(numerator, denominator) -}}
{%- endmacro %}

{% macro bigquery__dex_continuity_floordiv(numerator, denominator) -%}
cast(floor(cast({{ numerator }} as float64) / {{ denominator }}) as int64)
{%- endmacro %}

{% macro clickhouse__dex_continuity_floordiv(numerator, denominator) -%}
toInt64(floor(toFloat64({{ numerator }}) / {{ denominator }}))
{%- endmacro %}

{# --- the previous bucket of the same key --- #}

{% macro default__dex_continuity_lag(expression, partition_by, order_by) -%}
lag({{ expression }}) over ({% if partition_by %}partition by {{ partition_by }} {% endif %}order by {{ order_by }})
{%- endmacro %}

{#- ClickHouse has no LAG. lagInFrame reads only inside the frame, so the frame
    is spelled out, and fills the first row with the type's default, so the
    value is made nullable with an explicit NULL default. -#}
{% macro clickhouse__dex_continuity_lag(expression, partition_by, order_by) -%}
lagInFrame(toNullable({{ expression }}), 1, NULL) over ({% if partition_by %}partition by {{ partition_by }} {% endif %}order by {{ order_by }} rows between unbounded preceding and current row)
{%- endmacro %}
