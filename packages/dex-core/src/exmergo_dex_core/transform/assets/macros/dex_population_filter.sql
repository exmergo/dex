{#-
  dex_population_filter: a column test for a declared population filter.

  Generated by Dex from a model's declaration (`population.filters`, each a
  column and the values it `includes` or `excludes`) when
  `declarations.render_tests` in `.dex/config.yml` turns it on (#1453). One test
  per list. It fails when a row breaks the filter, and agrees with
  `maintain verify`'s population check (`population_contradicted`), row for row:

  - `excludes`: a row whose column holds an excluded value. A NULL is no value,
    so it never breaks an `excludes` list.
  - `includes`: a row whose column holds a value outside the list, and a NULL
    counts as outside it.

  Values are compared the way `maintain verify` compares them: as text when any
  listed value is text or the column is a text column (the column cast to the
  warehouse's string type, booleans written `true` and `false`), and as written
  otherwise. Only where every listed value is a number or a boolean does the
  test read the column's type, from the relation's metadata; where that read
  finds nothing (an ephemeral model, a mutant `transform test --mutate` builds),
  the values are compared as written.

  Counts only. The test returns one row holding the number of rows that break
  the filter, or no row when none does, and never a value from the column, so a
  test materialization that samples failing rows (Elementary's) has nothing to
  keep. `fail_calc` makes dbt's `failures` that number, the `contradicting_rows`
  `maintain verify` reports.

  One implementation per dialect through dbt's dispatch: the default holds on
  every warehouse Dex supports. Override one dialect with a
  `<adapter>__dex_population_filter(model, column_name, includes, excludes)`
  macro in the project. The text comparison's cast is dispatched on its own,
  `dex_population_filter_text(column_name)`: ClickHouse refuses to cast a NULL
  to its non-Nullable `String`, so it uses `toString`, which keeps a NULL.
-#}

{% test dex_population_filter(model, column_name, includes=none, excludes=none) %}
    {{ config(fail_calc='coalesce(sum(dex_violating_rows), 0)') }}
    {{ return(adapter.dispatch('dex_population_filter')(model, column_name, includes, excludes)) }}
{% endtest %}

{% macro default__dex_population_filter(model, column_name, includes, excludes) %}
{%- set values = excludes if excludes else includes -%}
{%- if not values -%}
    {{ exceptions.raise_compiler_error(
        "dex_population_filter on " ~ column_name ~ " lists no value: give it the "
        ~ "`includes` or `excludes` the declaration states"
    ) }}
{%- endif -%}
{%- set as_text = namespace(on=false) -%}
{%- for value in values if value is string -%}
    {%- set as_text.on = true -%}
{%- endfor -%}
{%- if not as_text.on and execute -%}
    {%- for column in adapter.get_columns_in_relation(model)
        if column.name | lower == column_name | lower and column.is_string() -%}
        {%- set as_text.on = true -%}
    {%- endfor -%}
{%- endif -%}
{%- set literals = [] -%}
{%- for value in values -%}
    {%- if as_text.on -%}
        {%- if value is boolean -%}
            {%- set text = 'true' if value else 'false' -%}
        {%- else -%}
            {%- set text = value | string -%}
        {%- endif -%}
        {%- do literals.append("'" ~ text | replace("'", "''") ~ "'") -%}
    {%- elif value is boolean -%}
        {%- do literals.append('TRUE' if value else 'FALSE') -%}
    {%- else -%}
        {%- do literals.append(value | string) -%}
    {%- endif -%}
{%- endfor -%}
{%- set subject = column_name -%}
{%- if as_text.on -%}
    {%- set subject = adapter.dispatch('dex_population_filter_text')(column_name) -%}
{%- endif -%}
select dex_violating_rows
from (
    select count(*) as dex_violating_rows
    from {{ model }}
    {%- if excludes %}
    where {{ subject }} in ({{ literals | join(', ') }})
    {%- else %}
    where {{ column_name }} is null or {{ subject }} not in ({{ literals | join(', ') }})
    {%- endif %}
) as dex_violations
where dex_violating_rows > 0
{% endmacro %}

{% macro default__dex_population_filter_text(column_name) %}cast({{ column_name }} as {{ dbt.type_string() }}){% endmacro %}

{% macro clickhouse__dex_population_filter_text(column_name) %}toString({{ column_name }}){% endmacro %}
