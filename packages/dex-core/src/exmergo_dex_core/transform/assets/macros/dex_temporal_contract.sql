{#-
  dex_temporal_contract: a model-level test for one measure of a declared history.

  Generated by Dex from a model's declaration (`history`: the snapshot the model
  reads, the `entity` key, the `status` column and its target, the policies, and
  the `measures` the model outputs) when `declarations.render_tests` in
  `.dex/config.yml` turns it on (#1458). One test per declared measure, told
  apart by `measure`, each failing with the number of entities whose column
  disagrees with the value the snapshot's versions and the declared policy give:

  - `transition_count`: `maintain verify`'s `temporal_transition_count_mismatch`
  - `latest_target_transition_at`: `temporal_latest_transition_mismatch`
  - `first_target_at`: `temporal_first_attainment_mismatch`

  each count the finding's `mismatched_entities`. The expected values come from
  the snapshot alone, never from the model's SQL, as `maintain verify` derives
  them: versions ordered by the snapshot's validity column (`order_column`,
  `dbt_valid_from` unless the snapshot renames it), a transition a change of
  status between consecutive versions, a first observation at the target a
  transition only under `initial_observation: transition`, a NULL status a
  state of its own only under `null_status: state`.

  Entities `maintain verify` excludes are excluded here too, by the same rules:
  versions sharing one validity time (their order is undefined), and, under a
  `business` time, a status change whose timestamp runs backwards (business and
  capture order disagree). Under a `business` time, the time measures also skip
  an entity whose timestamp is NULL or stands still at a change. A model row
  whose key repeats is compared once per row, as `maintain verify` compares it.

  A measure whose value depends on a policy the declaration leaves out renders
  no test (`policy_missing`): none is assumed. Given one by hand, this macro
  refuses to compile rather than assume it.

  Counts only. The test returns one row holding the count, or no row when it is
  zero, and never a key, so a test materialization that samples failing rows
  (Elementary's) has nothing to keep. It scans the whole snapshot twice (a
  window over each entity's versions, and its distinct entities) and the whole
  model, so it is tagged `dex_scheduled`.

  One implementation per dialect through dbt's dispatch: the default holds on
  every warehouse Dex supports, with these pieces dispatched on their own, each
  written as `maintain verify` writes it on each warehouse:
  `dex_temporal_contract_text(column_name)` (a text cast; ClickHouse uses
  `toString`), `dex_temporal_contract_literal(text)` (a text literal),
  `dex_temporal_contract_timestamp()` (the timestamp type a cast names), and
  `dex_temporal_contract_lag(expression, partition_by, order_by)` (the previous
  version's value; ClickHouse has no `LAG`). Override one dialect with a
  `<adapter>__dex_temporal_contract(...)` macro in the project.
-#}

{% test dex_temporal_contract(model, snapshot, entity, status_column, target, measure, measure_column, order_column='dbt_valid_from', time_column=none, initial_observation=none, null_status=none, provenance=none) %}
    {{ config(fail_calc='coalesce(sum(dex_mismatched_entities), 0)') }}
    {{ return(adapter.dispatch('dex_temporal_contract')(model, snapshot, entity, status_column, target, measure, measure_column, order_column, time_column, initial_observation, null_status, provenance)) }}
{% endtest %}

{% macro default__dex_temporal_contract(model, snapshot, entity, status_column, target, measure, measure_column, order_column, time_column, initial_observation, null_status, provenance) %}
{%- set owed_by = {
    'transition_count': ['initial_observation', 'null_status'],
    'latest_target_transition_at': ['initial_observation', 'null_status', 'provenance'],
    'first_target_at': ['provenance'],
} -%}
{%- if measure not in owed_by -%}
    {{ exceptions.raise_compiler_error(
        "dex_temporal_contract on " ~ model ~ " takes measure 'transition_count', "
        ~ "'latest_target_transition_at' or 'first_target_at', not '" ~ measure ~ "'"
    ) }}
{%- endif -%}
{%- set given = {
    'initial_observation': initial_observation,
    'null_status': null_status,
    'provenance': provenance,
} -%}
{%- for policy in owed_by[measure] if given[policy] is none -%}
    {{ exceptions.raise_compiler_error(
        "dex_temporal_contract on " ~ model ~ " checks " ~ measure ~ ", whose value "
        ~ "depends on `" ~ policy ~ "`, which it was not given; Dex assumes no "
        ~ "temporal policy, so state it in the model's history declaration"
    ) }}
{%- endfor -%}
{%- if not entity -%}
    {{ exceptions.raise_compiler_error(
        "dex_temporal_contract on " ~ model ~ " maps no entity column: give it the "
        ~ "`entity` the declaration's history states"
    ) }}
{%- endif -%}
{#- Each declared name resolved to its physical spelling and quoted, as
    maintain verify matches a declared name against the live columns, case
    folded, and quotes the column it finds. A name the metadata does not hold
    (no metadata at parse time, an ephemeral model) is written as declared. -#}
{%- set snapshot_columns = {} -%}
{%- set model_columns = {} -%}
{%- if execute -%}
    {%- for column in adapter.get_columns_in_relation(snapshot) -%}
        {%- do snapshot_columns.update({column.name | lower: column}) -%}
    {%- endfor -%}
    {%- for column in adapter.get_columns_in_relation(model) -%}
        {%- do model_columns.update({column.name | lower: column}) -%}
    {%- endfor -%}
{%- endif -%}
{%- set outs = [] -%}
{%- for column in entity.keys() -%}{%- do outs.append(dex_temporal_contract_resolved(column, model_columns)) -%}{%- endfor -%}
{%- set snaps = [] -%}
{%- for column in entity.values() -%}{%- do snaps.append(dex_temporal_contract_resolved(column, snapshot_columns)) -%}{%- endfor -%}
{%- set status_found = snapshot_columns.get(status_column | replace('"', '') | replace('`', '') | lower) -%}
{%- set measure_found = model_columns.get(measure_column | replace('"', '') | replace('`', '') | lower) -%}
{%- set status_name = dex_temporal_contract_resolved(status_column, snapshot_columns) -%}
{%- set order_name = dex_temporal_contract_resolved(order_column, snapshot_columns) -%}
{%- set time = dex_temporal_contract_resolved(time_column if time_column else order_column, snapshot_columns) -%}
{%- set measure_name = dex_temporal_contract_resolved(measure_column, model_columns) -%}
{%- set timed = measure != 'transition_count' -%}
{%- set business = provenance == 'business' -%}

{#- The status compared as text where the target is text or the column is a
    text column, and as written otherwise, as maintain verify compares it. -#}
{%- set string_column = status_found is not none and status_found.is_string() -%}
{%- set measure_is_date = measure_found is not none and (measure_found.dtype | lower) == 'date' -%}
{%- set as_text = target is string or string_column -%}
{%- if as_text -%}
    {%- if target is boolean -%}
        {%- set literal = adapter.dispatch('dex_temporal_contract_literal')('true' if target else 'false') -%}
    {%- else -%}
        {%- set literal = adapter.dispatch('dex_temporal_contract_literal')(target | string) -%}
    {%- endif -%}
{%- elif target is boolean -%}
    {%- set literal = 'TRUE' if target else 'FALSE' -%}
{%- else -%}
    {%- set literal = target | string -%}
{%- endif -%}
{%- set subject = status_name -%}
{%- if as_text and status_found is not none and not string_column -%}
    {%- set subject = adapter.dispatch('dex_temporal_contract_text')(status_name) -%}
{%- endif -%}
{%- set timestamp = adapter.dispatch('dex_temporal_contract_timestamp')() -%}
{%- set measure_type = 'date' if measure_is_date else timestamp -%}

{%- set keys = [] -%}
{%- for column in snaps -%}{%- do keys.append('dex_k' ~ loop.index0) -%}{%- endfor -%}
{%- set key_list = keys | join(', ') -%}
{%- set snap_not_null = [] -%}
{%- for column in snaps -%}{%- do snap_not_null.append(column ~ ' is not null') -%}{%- endfor -%}
{%- set keep = snap_not_null | join(' and ') -%}
{%- if null_status != 'state' -%}
    {%- set keep = keep ~ ' and ' ~ status_name ~ ' is not null' -%}
{%- endif -%}
{%- set out_not_null = [] -%}
{%- for column in outs -%}{%- do out_not_null.append(column ~ ' is not null') -%}{%- endfor -%}
{%- set entered_first = '1' if initial_observation == 'transition' else '0' -%}
{%- set expected = {
    'transition_count': 'b.dex_n',
    'latest_target_transition_at': 'cast(b.dex_latest as ' ~ measure_type ~ ')',
    'first_target_at': 'cast(b.dex_first as ' ~ measure_type ~ ')',
}[measure] -%}
{%- set observed = 'o.dex_m' -%}

with dex_versions as (
    select
    {%- for column in snaps %}
        {{ column }} as dex_k{{ loop.index0 }},
    {%- endfor %}
        {{ status_name }} as dex_s,
        {{ order_name }} as dex_o,
        {{ time }} as dex_t,
        case when {{ subject }} = {{ literal }} then 1 else 0 end as dex_target
    from {{ snapshot }}
    where {{ keep }}
),
dex_lagged as (
    select
        {{ key_list }}, dex_s, dex_o, dex_t, dex_target,
        {{ adapter.dispatch('dex_temporal_contract_lag')('dex_s', key_list, 'dex_o') }} as dex_prev_s,
        {{ adapter.dispatch('dex_temporal_contract_lag')('dex_t', key_list, 'dex_o') }} as dex_prev_t,
        row_number() over (partition by {{ key_list }} order by dex_o) as dex_rn
    from dex_versions
),
dex_steps as (
    select
        {{ key_list }}, dex_o, dex_t, dex_target, dex_prev_t,
        case
            when dex_rn = 1 then 0
            when (case when dex_s = dex_prev_s then 1
                       when dex_s is null and dex_prev_s is null then 1 else 0 end = 1) then 0
            else 1
        end as dex_changed,
        case when dex_rn = 1 and dex_target = 1 then {{ entered_first }} else 0 end as dex_entered_first
    from dex_lagged
),
dex_expected as (
    select
        {{ key_list }},
        sum(dex_changed + dex_entered_first) as dex_n,
        max(case when dex_target = 1 and (dex_changed = 1 or dex_entered_first = 1)
                 then cast(dex_t as {{ timestamp }}) end) as dex_latest,
        min(case when dex_target = 1 then cast(dex_t as {{ timestamp }}) end) as dex_first,
        {%- if business %}
        sum(case when dex_changed = 1 and dex_t < dex_prev_t then 1 else 0 end) as dex_conflict,
        sum(case when (dex_changed = 1 or dex_target = 1) and dex_t is null then 1
                 when dex_changed = 1 and dex_t = dex_prev_t then 1 else 0 end) as dex_unreliable,
        {%- else %}
        0 as dex_conflict,
        0 as dex_unreliable,
        {%- endif %}
        count(*) - count(distinct dex_o) as dex_ambiguous,
        {#- A row of its own, so an entity with no version kept reads NULL
            where a warehouse fills an unmatched join with defaults. -#}
        1 as dex_seen
    from dex_steps
    group by {{ key_list }}
),
dex_entities as (
    select distinct
    {%- for column in snaps %}
        {{ column }} as dex_k{{ loop.index0 }}{{ ',' if not loop.last }}
    {%- endfor %}
    from {{ snapshot }}
    where {{ snap_not_null | join(' and ') }}
),
dex_base as (
    select
    {%- for key in keys %}
        e.{{ key }},
    {%- endfor %}
        case when x.dex_seen = 1 then x.dex_n else 0 end as dex_n,
        case when x.dex_seen = 1 then x.dex_latest end as dex_latest,
        case when x.dex_seen = 1 then x.dex_first end as dex_first,
        case when x.dex_seen = 1 then x.dex_unreliable else 0 end as dex_unreliable,
        case when x.dex_seen = 1 and (x.dex_conflict <> 0 or x.dex_ambiguous <> 0)
             then 0 else 1 end as dex_clean
    from dex_entities e
    left join dex_expected x
    on {% for key in keys -%}
        e.{{ key }} = x.{{ key }}{{ ' and ' if not loop.last }}
    {%- endfor %}
),
dex_out as (
    select
    {%- for column in outs %}
        {{ column }} as dex_k{{ loop.index0 }},
    {%- endfor %}
        {%- if timed %}
        cast({{ measure_name }} as {{ measure_type }}) as dex_m,
        {%- else %}
        {{ measure_name }} as dex_m,
        {%- endif %}
        1 as dex_hit
    from {{ model }}
    where {{ out_not_null | join(' and ') }}
)
select dex_mismatched_entities
from (
    select count(case
        when o.dex_hit = 1 and b.dex_clean = 1
            {%- if timed %} and b.dex_unreliable = 0{% endif %}
            and not (case when {{ observed }} = {{ expected }} then 1
                          when {{ observed }} is null and {{ expected }} is null then 1
                          else 0 end = 1)
        then 1 end) as dex_mismatched_entities
    from dex_base b
    left join dex_out o
    on {% for key in keys -%}
        b.{{ key }} = o.{{ key }}{{ ' and ' if not loop.last }}
    {%- endfor %}
) as dex_violations
where dex_mismatched_entities > 0
{% endmacro %}

{#- ``name`` as the column ``columns`` (folded name -> column) holds,
    quoted, or as written where it holds none. -#}
{% macro dex_temporal_contract_resolved(name, columns) -%}
    {%- set found = columns.get(name | replace('"', '') | replace('`', '') | lower) -%}
    {{- adapter.quote(found.name) if found is not none else name -}}
{%- endmacro %}

